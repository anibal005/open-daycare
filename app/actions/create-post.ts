"use server";

import { revalidatePath } from "next/cache";
import { POST_TYPE_ORDER, type PostType } from "@/lib/posts";
import { createClient } from "@/lib/supabase/server";

export interface CreatePostPhotoInput {
  storagePath: string; // "<daycare_id>/<post_id>/<position>.<webp|jpg>"
  alt: string;
  width: number;
  height: number;
}

export interface CreatePostInput {
  postId: string; // uuid v4 generated by the browser
  type: PostType;
  body: string;
  recipientChildIds: string[]; // [] = whole room
  photos: CreatePostPhotoInput[]; // 0..2
}

export type CreatePostResult =
  | { ok: true; postId: string }
  | { ok: false; error: string };

const UUID_V4_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const UUID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

const MAX_BODY_LENGTH = 2000;
const MAX_RECIPIENTS = 100;
const MAX_PHOTOS = 2;
const MAX_ALT_LENGTH = 300;
const MAX_PHOTO_DIMENSION = 10000;

const INVALID_DATA_ERROR = "Los datos de la publicación no son válidos";
const SESSION_ERROR = "Tu sesión expiró. Volvé a iniciar sesión.";
const PERMISSION_ERROR = "No tenés permiso para publicar";
const GENERIC_ERROR = "No se pudo publicar. Intentá nuevamente.";

// Row shape read by this action. The Supabase helpers in `lib/supabase/*` are
// not instantiated with the generated `Database` type, so the columns used here
// are declared locally (same pattern as `app/staff/children/[id]/page.tsx`).
interface ProfileRow {
  id: string;
  daycare_id: string;
  role: string;
  status: string;
}

function isValidDimension(value: number) {
  return (
    Number.isInteger(value) && value >= 1 && value <= MAX_PHOTO_DIMENSION
  );
}

function mapRpcError(code: string | undefined) {
  switch (code) {
    case "42501":
      return PERMISSION_ERROR;
    case "23514":
      return "Revisá los datos de la publicación";
    case "23503":
      return "Uno de los niños ya no está disponible";
    case "22P02":
    case "22023":
      return INVALID_DATA_ERROR;
    default:
      return GENERIC_ERROR;
  }
}

export async function createPost(
  input: CreatePostInput,
): Promise<CreatePostResult> {
  const body = typeof input.body === "string" ? input.body.trim() : "";

  if (!UUID_V4_PATTERN.test(input.postId ?? "")) {
    return { ok: false, error: INVALID_DATA_ERROR };
  }

  if (!POST_TYPE_ORDER.includes(input.type)) {
    return { ok: false, error: INVALID_DATA_ERROR };
  }

  if (body.length === 0 || body.length > MAX_BODY_LENGTH) {
    return { ok: false, error: INVALID_DATA_ERROR };
  }

  const recipientChildIds = Array.isArray(input.recipientChildIds)
    ? input.recipientChildIds
    : [];

  if (
    recipientChildIds.length > MAX_RECIPIENTS ||
    recipientChildIds.some((id) => !UUID_PATTERN.test(id)) ||
    new Set(recipientChildIds).size !== recipientChildIds.length
  ) {
    return { ok: false, error: INVALID_DATA_ERROR };
  }

  const photos = Array.isArray(input.photos) ? input.photos : [];

  if (photos.length > MAX_PHOTOS) {
    return { ok: false, error: INVALID_DATA_ERROR };
  }

  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    return { ok: false, error: SESSION_ERROR };
  }

  const { data: profile, error: profileError }: {
    data: ProfileRow | null;
    error: { code: string } | null;
  } = await supabase
    .from("users")
    .select("id, daycare_id, role, status")
    .eq("id", user.id)
    .single();

  if (profileError) {
    console.error("[create-post] Failed to load profile", profileError.code);
    return { ok: false, error: GENERIC_ERROR };
  }

  if (
    !profile ||
    profile.status !== "active" ||
    (profile.role !== "staff" && profile.role !== "admin")
  ) {
    return { ok: false, error: PERMISSION_ERROR };
  }

  const storagePathPrefix = `${profile.daycare_id}/${input.postId}/`;

  for (const photo of photos) {
    if (
      typeof photo.storagePath !== "string" ||
      !photo.storagePath.startsWith(storagePathPrefix) ||
      !isValidDimension(photo.width) ||
      !isValidDimension(photo.height) ||
      typeof photo.alt !== "string"
    ) {
      return { ok: false, error: INVALID_DATA_ERROR };
    }
  }

  const { data: createdId, error } = await supabase.rpc("create_post", {
    p_id: input.postId,
    p_type: input.type,
    p_body: body,
    p_child_ids: recipientChildIds,
    p_photos: photos.map((photo) => ({
      storage_path: photo.storagePath, // snake_case: the RPC reads photo->>'storage_path'
      alt: photo.alt.trim().slice(0, MAX_ALT_LENGTH),
      width: photo.width,
      height: photo.height,
    })),
  });

  if (error) {
    console.error("[create-post] Failed to create post", {
      code: error.code,
      message: error.message,
    });
    return { ok: false, error: mapRpcError(error.code) };
  }

  revalidatePath("/staff");
  revalidatePath("/family");

  return {
    ok: true,
    postId: typeof createdId === "string" ? createdId : input.postId,
  };
}
